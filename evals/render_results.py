"""Render docs/EVAL_RESULTS.md from reports/*.json. Every number in that file comes from here.

uv run python evals/render_results.py
"""

import json
import statistics
from collections import defaultdict

from common import REPORTS, ROOT


def load(name: str):
    p = REPORTS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def fmt(v, nd=3):
    if v is None:
        return "not measured"
    return f"{v:.{nd}f}" if isinstance(v, float) else str(v)


def factor_effects(grid: dict) -> list[tuple]:
    """Average each metric over all configs at each factor level (marginal means)."""
    rows = []
    for factor in ("rerank", "hybrid", "chunk_size", "top_k", "store"):
        levels = defaultdict(list)
        for r in grid["all"]:
            levels[r["config"][factor]].append(r["metrics"])
        for level, ms in sorted(levels.items(), key=lambda x: str(x[0])):
            rows.append(
                (
                    factor,
                    level,
                    *(
                        statistics.mean(m[k] for m in ms)
                        for k in ("recall_at_k", "mrr", "no_answer_accuracy", "latency_p50_ms")
                    ),
                )
            )
    return rows


MICRO = None
STACK_SETTINGS = [  # fixed settings for the store/stack comparison table
    ("chunk 300, k 5, rerank, hybrid (production settings)", 300, 5, True, True),
    ("chunk 300, k 5, no rerank, hybrid", 300, 5, False, True),
    ("chunk 300, k 5, no rerank, vector-only", 300, 5, False, False),
]


def _store_section(w, grid: dict) -> None:
    by = {
        (
            r["config"]["chunk_size"],
            r["config"]["top_k"],
            r["config"]["rerank"],
            r["config"]["hybrid"],
            r["config"]["store"],
        ): r["metrics"]
        for r in grid["all"]
    }
    stores = [s for s in ("chroma", "faiss", "pgvector", "llamaindex") if any(k[4] == s for k in by)]
    w(
        "- **Stores and frameworks** (same chunks, same embedding model, same role filter; hybrid means Python "
        "BM25 + RRF for Chroma/FAISS, Postgres full-text + RRF in one SQL query for pgvector, and BM25Retriever + "
        "QueryFusionRetriever for LlamaIndex):\n"
    )
    w("  | Settings | " + " | ".join(stores) + " |\n  |---|" + "---|" * len(stores))
    for label, cs, k, rr, hy in STACK_SETTINGS:
        cells = []
        for st in stores:
            m = by.get((cs, k, rr, hy, st))
            cells.append(f"MRR {m['mrr']:.3f}, p50 {m['latency_p50_ms']:.0f} ms" if m else "not run")
        w(f"  | {label} | " + " | ".join(cells) + " |")
    w("")
    if MICRO:
        parts = [f"{name} {v['median']} ms" for name, v in MICRO["results_ms"].items()]
        w(
            f"  Raw store call, top-20 with the role filter, median over {MICRO['n_queries']} queries x "
            f"{MICRO['repeats']} (`reports/store_microbench.json`): " + "; ".join(parts) + ". At ~90 chunks every "
            "store answers in a few milliseconds, so end-to-end differences in the grid come mostly from reranking "
            "and run-to-run noise, not from the store."
        )
    # Hybrid vs vector-only without rerank, per store: computed, not asserted.
    comp = []
    for st in stores:
        h, v = by.get((300, 5, False, True, st)), by.get((300, 5, False, False, st))
        if h and v:
            word = "higher" if h["mrr"] > v["mrr"] else "lower" if h["mrr"] < v["mrr"] else "the same"
            comp.append(f"{st} {h['mrr']:.3f} vs {v['mrr']:.3f} ({word})")
    w(
        "  Reading: with reranking on, all stacks reach the same quality, because the cross-encoder decides the "
        "final ranking. Without reranking, the keyword side matters. Hybrid vs vector-only MRR (chunk 300, k 5): "
        + "; ".join(comp)
        + ". Differences of this size are one or two questions out of 40. "
        "Chroma stays the default when there is no Postgres; with DATABASE_URL set, `VECTOR_BACKEND=auto` uses "
        "pgvector so data, vectors and keyword search live in one database (one backup, one access-control model, "
        "joins with business data)."
    )


def main() -> None:
    ret, grid, safety = load("retrieval_eval.json"), load("grid_results.json"), load("safety_eval.json")
    safety_llm, gen, perf = load("safety_eval_llm.json"), load("generation_eval.json"), load("perf_eval.json")
    bench, calib = load("embedding_benchmark.json"), load("semantic_cache_calibration.json")
    global MICRO
    MICRO = load("store_microbench.json")
    router = load("router_comparison.json")
    L = []
    w = L.append

    w("# Evaluation Results\n")
    w(
        "> Generated by `evals/render_results.py` from `reports/*.json`. Do not edit numbers by hand: "
        "re-run the scripts and re-render.\n"
    )
    w(
        "Corpus: 12 fictional documents. Golden set: 40 questions (`evals/golden.jsonl`): 21 single-source, "
        "5 multi-document, 5 follow-ups, 5 unanswerable, 4 role-restricted.\n"
    )

    # ---------------- production retrieval ----------------
    m = ret["metrics"]
    w("## 1. Retrieval (production config, no API key needed)\n")
    w(f"Config: `{json.dumps(ret['config'])}`\n")
    w("| Metric | Value |\n|---|---|")
    w(f"| recall@5 | {fmt(m['recall_at_k'])} |")
    w(f"| MRR | {fmt(m['mrr'])} |")
    w(f"| No-answer accuracy (retrieval-level: refuse iff unanswerable) | {fmt(m['no_answer_accuracy'])} |")
    w(f"| Refusal rate on unanswerable + restricted questions | {fmt(m['refusal_rate_on_unanswerable'])} |")
    w(f"| False refusal rate on answerable questions | {fmt(m['false_refusal_rate_on_answerable'])} |")
    w(f"| Access-control leaks on the golden set | {m['leaks']} |")
    lt = ret["leak_test"]
    w(
        f"| **Adversarial leak test** (restricted chunk text, headings, first sentences as queries; vector, hybrid, "
        f"hybrid+rerank; every role) | **{lt['leaks']} leaks in {lt['queries']} queries** |"
    )
    w(f"| Retrieval latency p50 / p95 | {m['latency_p50_ms']} ms / {m['latency_p95_ms']} ms |\n")
    st = ret["stage_latency_ms_median"]
    w("Median stage latency: " + ", ".join(f"{k} {v} ms" for k, v in st.items()) + ".\n")
    if ret["misses"]:
        w("Misses (wrongly refused, or expected source not retrieved):\n")
        for x in ret["misses"]:
            w(
                f'- `{x["id"]}` "{x["question"]}" (role {x["role"]}): top rerank score {x["top_score"]}, '
                f"found={x['found']}, top hits {x['retrieved']}"
            )
        w("")
    sweep = ret["threshold_sweep"]
    best_t = max(sweep, key=lambda r: r["no_answer_accuracy"])
    cur = next(r for r in sweep if r["threshold"] == -4)
    w(
        f"**Relevance threshold.** The production threshold is a cross-encoder logit of -4, chosen from a handful "
        f"of probe questions *before* the golden set existed. On the golden set it gives {fmt(cur['no_answer_accuracy'])} "
        f"no-answer accuracy; the best value in the sweep is {best_t['threshold']} "
        f"({fmt(best_t['no_answer_accuracy'])}). I did **not** move the threshold to the sweep's best value: "
        f"tuning it on the same 40 questions we report on would inflate the score (a one-question gain on a "
        f"40-question set is 2.5 points). A held-out set is needed before changing it.\n"
    )

    # ---------------- grid ----------------
    w(f"## 2. Experiment grid (retrieval-only, {len(grid['all'])} configs, logged to MLflow)\n")
    w(
        "Factors: chunk size {100, 300} x top-k {3, 5} x rerank on/off x hybrid (vector+BM25, RRF) vs vector-only "
        "x store/stack (Chroma, FAISS, pgvector with in-database full-text hybrid, and a LlamaIndex retrieval "
        "stack over the same chunks). Logged to the MLflow experiment `orbitdesk-retrieval-grid` "
        "(`uv run mlflow ui --backend-store-uri sqlite:///mlruns/mlflow.db`). Ranking rule: "
        f"{grid['ranking_rule']}.\n"
    )
    w("| Rank | Config | recall@k | MRR | no-answer acc. | p50 ms | leaks |\n|---|---|---|---|---|---|---|")
    for i, r in enumerate(grid["all"], 1):
        mm = r["metrics"]
        tag = " (baseline)" if r["name"] == grid["baseline"]["name"] else ""
        w(
            f"| {i} | `{r['name']}`{tag} | {mm['recall_at_k']:.3f} | {mm['mrr']:.3f} | {mm['no_answer_accuracy']:.3f} "
            f"| {mm['latency_p50_ms']:.0f} | {mm['leaks']} |"
        )
    if grid.get("not_run"):
        w(f"\nNot run: {len(grid['not_run'])} configs ({grid['not_run_reason']}).")
    w("\n**Effect of each factor** (mean over all configs at each level):\n")
    w("| Factor | Level | recall@k | MRR | no-answer acc. | p50 ms |\n|---|---|---|---|---|---|")
    effects = factor_effects(grid)
    (REPORTS / "grid_factor_effects.json").write_text(
        json.dumps(
            [
                {
                    "factor": f,
                    "level": lv,
                    "recall_at_k": round(rc, 3),
                    "mrr": round(mrr, 3),
                    "no_answer_accuracy": round(na, 3),
                    "latency_p50_ms": round(lat),
                }
                for f, lv, rc, mrr, na, lat in effects
            ],
            indent=2,
        ),
        encoding="utf-8",
    )
    for f, lv, rc, mrr, na, lat in effects:
        w(f"| {f} | {lv} | {rc:.3f} | {mrr:.3f} | {na:.3f} | {lat:.0f} |")
    eff = {(f, str(lv)): (rc, mrr, na, lat) for f, lv, rc, mrr, na, lat in effects}
    best, base = grid["best"][0], grid["baseline"]
    w("\n### Which config won, and why\n")
    w(
        f"- **Winner: `{best['name']}`** (recall@5 {best['metrics']['recall_at_k']:.3f}, MRR "
        f"{best['metrics']['mrr']:.3f}, no-answer accuracy {best['metrics']['no_answer_accuracy']:.3f}, p50 "
        f"{best['metrics']['latency_p50_ms']:.0f} ms) vs baseline `{base['name']}` (recall@5 "
        f"{base['metrics']['recall_at_k']:.3f}, MRR {base['metrics']['mrr']:.3f}, no-answer accuracy "
        f"{base['metrics']['no_answer_accuracy']:.3f}, p50 {base['metrics']['latency_p50_ms']:.0f} ms)."
    )
    w(
        f"- **Reranking is the factor that matters.** Averaged over the grid it raises MRR from "
        f"{eff[('rerank', 'False')][1]:.3f} to {eff[('rerank', 'True')][1]:.3f} and no-answer accuracy from "
        f"{eff[('rerank', 'False')][2]:.3f} to {eff[('rerank', 'True')][2]:.3f}: the cross-encoder logit is a much "
        f'better "is this actually relevant?" signal than cosine similarity, so the refusal threshold works. '
        f"The price is latency ({eff[('rerank', 'False')][3]:.0f} ms to {eff[('rerank', 'True')][3]:.0f} ms p50), "
        f"almost all of it the cross-encoder on CPU."
    )
    w(
        f"- **Hybrid (BM25 + RRF) made no measurable difference here** (MRR {eff[('hybrid', 'False')][1]:.3f} "
        f"vector-only vs {eff[('hybrid', 'True')][1]:.3f} hybrid). The corpus is small and clean, and bge-small "
        f"already handles exact codes like VPN-809. Production keeps hybrid on because BM25 costs ~"
        f"{st.get('bm25_search', 0)} ms and is cheap insurance for identifier-heavy queries this golden set does "
        f"not stress, but this is a judgment call, not something the numbers prove."
    )
    w(
        f"- **Chunk size 100 vs 300:** MRR {eff[('chunk_size', '100')][1]:.3f} vs {eff[('chunk_size', '300')][1]:.3f}, "
        f"p50 {eff[('chunk_size', '100')][3]:.0f} vs {eff[('chunk_size', '300')][3]:.0f} ms. The latency gain is "
        f"consistent with the cross-encoder scoring shorter (query, chunk) pairs. The quality difference is within one question. Most sections in "
        f"these documents are shorter than 150 tokens, which is why the grid uses 100 vs 300 rather than 300 vs 500 "
        f"(at 300 and 500 the chunks would be identical)."
    )
    w(
        f"- **top-k 3 vs 5:** recall {eff[('top_k', '3')][0]:.3f} vs {eff[('top_k', '5')][0]:.3f}. In the production "
        f"config at k=3 the misses were the second source of two multi-document questions (q23, q26) and one "
        f"single-source question (q20) whose answer chunk ranked 4th."
    )
    _store_section(w, grid)
    w(
        "- **Production config:** rerank on, hybrid on, top-k 5, Chroma, chunk size 300. Switching to 100-token "
        "chunks would cut retrieval latency, but whether smaller chunks hurt answer faithfulness is what the "
        "generation eval (section 4) is for; the switch waits for that result."
    )
    w(
        "- **Caveat:** 40 questions on 12 documents is small; recall saturates at 1.0 for many configs, so the grid "
        "separates configs mainly on MRR, refusals and latency.\n"
    )

    # ---------------- safety ----------------
    w("## 3. Safety\n")
    inj = safety["injection"]
    w("| Check | Result |\n|---|---|")
    w(
        f"| Direct prompt injection blocked by **heuristics only** (no key) | {inj['direct']['passed']}/"
        f"{inj['direct']['n']} ({inj['direct']['pass_rate']:.2f}) |"
    )
    w(
        f"| Indirect injection (poisoned document text) flagged and dropped from context | {inj['indirect']['passed']}/"
        f"{inj['indirect']['n']} |"
    )
    w(
        f"| Benign look-alike questions NOT blocked (false-positive check) | {inj['benign_not_blocked']['passed']}/"
        f"{inj['benign_not_blocked']['n']} |"
    )
    if safety_llm:
        il = safety_llm["injection"]
        w(f"| Direct injection blocked by heuristics + Prompt Guard 2 | {il['direct']['passed']}/{il['direct']['n']} |")
        w(
            f"| Benign NOT blocked with Prompt Guard 2 | {il['benign_not_blocked']['passed']}/"
            f"{il['benign_not_blocked']['n']} |"
        )
    else:
        w(
            "| Direct injection with the Prompt Guard 2 layer | not measured yet (needs GROQ_API_KEY: "
            "`python evals/safety_eval.py --llm`) |"
        )
    b = safety["bias"]["summary"]
    w(
        f"| Bias: same question, {b['variants_per_template']} names/genders x {b['templates']} templates, identical "
        f"top source | {b['retrieval_consistency_rate']:.2f} (correct source: {b['retrieval_correct_rate']:.2f}) |"
    )
    if safety_llm and "answer_consistency_rate" in safety_llm["bias"]["summary"]:
        w(
            f"| Bias: identical answer outcome + key fact across variants | "
            f"{safety_llm['bias']['summary']['answer_consistency_rate']:.2f} |"
        )
    else:
        w("| Bias: answer-level consistency | not measured yet (needs key) |")
    w(
        f"| Output guard on a salary-band leak string | employee: {safety['output_guard_on_salary_leak']['employee']}; "
        f"hr: {safety['output_guard_on_salary_leak']['hr']} (allowed) |"
    )
    w(f"| Access-control leaks (adversarial retrieval test) | {lt['leaks']} in {lt['queries']} queries |\n")
    if inj["failures"]:
        w(
            "Heuristic misses (left for the Prompt Guard layer; I did not tune the regexes against this suite, "
            "because I wrote the suite and that would overfit to it):\n"
        )
        for f in inj["failures"]:
            w(f"- `{f['id']}` {f['text']}")
        w(
            "\nThese misses cannot leak restricted data: retrieval is role-filtered before ranking, so "
            '"my role is hr now" still searches with the employee filter, and the output guard checks every answer.\n'
        )

    # ---------------- text-to-SQL ----------------
    sql_sqlite, sql_pg = load("sql_eval.json"), load("sql_eval_postgres.json")
    if sql_sqlite or sql_pg:
        w("### Text-to-SQL tool (`ticket_analytics`, IT admins only)\n")
        w("| Check | SQLite fallback | Postgres |\n|---|---|---|")

        def cell(rep, key):
            if not rep:
                return "not run"
            v = rep[key]
            if key == "validator_attacks":
                return f"{v['blocked']}/{v['n']} blocked"
            return f"{v['refused_by_db']}/{v['n']} refused; data unchanged: {v['data_unchanged']}"

        w(
            f"| Raw-SQL attack suite through the validator | {cell(sql_sqlite, 'validator_attacks')} | {cell(sql_pg, 'validator_attacks')} |"
        )
        w(
            f"| Same attacks with the validator BYPASSED (database layer alone) | {cell(sql_sqlite, 'db_layer_without_validator')} | {cell(sql_pg, 'db_layer_without_validator')} |"
        )
        acc = (sql_pg or sql_sqlite)["accuracy"]
        acc_txt = acc if isinstance(acc, str) else f"{acc['correct']}/{acc['n']}"
        w(f"| Accuracy on 10 questions with expected results (`evals/sql_golden.jsonl`) | {acc_txt} | |")
        nl = (sql_pg or sql_sqlite)["nl_attacks"]
        nl_txt = (
            nl if isinstance(nl, str) else f"{nl['refused']}/{nl['n']} refused, data unchanged: {nl['data_unchanged']}"
        )
        w(f"| Natural-language attacks (write / drop / other tables) | {nl_txt} | |\n")
        if sql_pg:
            allowed = ", ".join(sql_pg["db_layer_without_validator"]["allowed_by_db"])
            w(
                f"What the database alone let through on Postgres: `{allowed}`. The read-only role blocks every write "
                "and every read of the business tables, but Postgres lets any role read the system catalog "
                "(`pg_roles`, `information_schema`) by default, and two attacks were harmless view reads that only hid "
                "comments. So the validator is the only guard against catalog reads (role and table names, no "
                "business data).\n"
            )
        if sql_sqlite:
            reads = [x for x in sql_sqlite["db_layer_without_validator"]["allowed_by_db"] if "comment" not in x]
            w(
                f"On the SQLite fallback the database blocks writes (`PRAGMA query_only`) but has no roles, so reads of "
                f"base tables (`{', '.join(reads)}`) are stopped only by the validator. Use Postgres when the "
                "analytics tool is exposed.\n"
            )

    # ---------------- generation ----------------
    w("## 4. Generation quality (RAGAS)\n")
    if gen and gen["configs"]:
        w(
            f"Status: **{gen['status']}**. Generator `{gen['generator']}`, judge `{gen['judge']}`. "
            "Faithfulness + answer relevancy are LLM-judged on answerable questions that were answered; "
            "context precision is RAGAS's ID-based metric (share of the top-k contexts that are a reference "
            "source, so with k=5 and one reference source its maximum is 0.2).\n"
        )
        w(
            "| Config | generated | judged | faithfulness | answer relevancy | context precision | no-answer acc. "
            "| answer leaks | mean tokens | est. cost / query |\n|---|---|---|---|---|---|---|---|---|---|"
        )
        for c in gen["configs"]:
            name = "cs{chunk_size}-k{top_k}-{rr}-{hy}-{store}-{prompt_version}".format(
                rr="rr" if c["config"]["rerank"] else "norr",
                hy="hyb" if c["config"]["hybrid"] else "vec",
                **c["config"],
            )
            w(
                f"| `{name}` | {c['n_generated']} | {c['n_judged']}/{c['n_judgeable']} | {fmt(c['faithfulness'])} | "
                f"{fmt(c['answer_relevancy'])} | {fmt(c['context_precision'])} | {fmt(c['no_answer_accuracy'])} | "
                f"{len(c['answer_leaks'])} | {fmt(c['mean_tokens'], 0)} | {fmt(c['mean_cost_usd'], 6)} |"
            )
        w("")
    else:
        w(
            "**Not measured yet.** Needs GROQ_API_KEY. Run `uv run --group eval python evals/generation_eval.py` "
            "(resumable across days on the free tier), then re-render this file. Planned runs: baseline, the two "
            "best grid configs, and the best config with prompt v2 (prompt v1 vs v2 comparison).\n"
        )

    # ---------------- performance ----------------
    w("## 5. Performance and cost\n")
    if perf and perf.get("mode") == "full pipeline":
        w(f"Generator `{perf['generator']}`, {perf['requests']} replayed requests.\n")
        w("| Stage | p50 ms | p95 ms |\n|---|---|---|")
        for k, v in perf["uncached_stages_ms"].items():
            w(f"| {k} | {v['p50']} | {v['p95']} |")
        w(
            f"\n- Cache hit rate in the replay: **{perf['cache_hit_rate']:.2f}** ({perf['cache_hits_by_kind']}); "
            f"semantic hits on paraphrases: {perf['semantic_hits_on_paraphrases']}/{perf['n_paraphrases']}."
        )
        w(f"- Cached answer latency p50 / p95: {perf['cached_total_ms']['p50']} / {perf['cached_total_ms']['p95']} ms.")
        w(
            f"- Tokens per uncached query: {perf['tokens_per_uncached_query']}; estimated cost per uncached query: "
            f"${fmt(perf['est_cost_per_uncached_query_usd'], 6)} (paid-plan list price; free tier is not billed).\n"
        )
    else:
        w("Retrieval-only (no key yet):\n")
        w("| Stage | p50 ms | p95 ms |\n|---|---|---|")
        for k, v in perf["stages_ms"].items():
            w(f"| {k} | {v['p50']} | {v['p95']} |")
        w(f"| **retrieval total** | {perf['total_retrieval_ms']['p50']} | {perf['total_retrieval_ms']['p95']} |\n")
        w(
            "LLM latency, tokens per query, cost per query and cache hit rate: **not measured yet** "
            "(needs GROQ_API_KEY: `uv run python evals/perf_eval.py`).\n"
        )
    if bench:
        r = bench["results"]
        w(
            f"**Embedding throughput** ({bench['n_chunks']} chunks, {bench['machine']['cpu_count']} CPU threads, "
            f"median of {bench['repeats']}): one-by-one {r['one_by_one']['chunks_per_s']} chunks/s; batch 8 "
            f"{r['batch_8']['chunks_per_s']} ({r['batch_8']['speedup_vs_one_by_one']}x); batch 32 "
            f"{r['batch_32']['chunks_per_s']} ({r['batch_32']['speedup_vs_one_by_one']}x); batch 64 "
            f"{r['batch_64']['chunks_per_s']} ({r['batch_64']['speedup_vs_one_by_one']}x). Batch 64 was no faster "
            "than one-by-one on this CPU (not profiled; padding every text to the longest in its batch is a likely "
            "cause), so ingestion uses batch 8.\n"
        )
    if calib:
        worst = max(calib["near_misses"], key=lambda p: p["cosine"])
        w(
            f"**Semantic cache threshold** ({calib['configured_threshold']}): max near-miss cosine "
            f'{calib["max_near_miss_cosine"]} ("{worst["a"]}" vs "{worst["b"]}"), so the threshold gives '
            f"{calib['false_hits_at_threshold']}/{calib['n_near_misses']} false hits and "
            f"{calib['paraphrase_hits_at_threshold']}/{calib['n_paraphrases']} paraphrase hits. Wrong answers cost "
            "more than cache misses, so the threshold stays conservative.\n"
        )

    if router:
        w("## 6. Router: fine-tuned vs prompt-only\n")
        w("See `reports/router_comparison.json` and section 6 in docs/INTERVIEW_MAP.md.\n")

    w("## Known limitations\n")
    w("- Golden set written by the same person who wrote the documents; questions are cleaner than real users'.")
    w("- The LLM judge (gpt-oss-20b) is from the same family as the generator (gpt-oss-120b); see docs/DECISIONS.md.")
    w("- Thresholds were picked before the golden set existed and are not re-tuned on it; no held-out set yet.")
    (ROOT / "docs" / "EVAL_RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/EVAL_RESULTS.md")


if __name__ == "__main__":
    main()
